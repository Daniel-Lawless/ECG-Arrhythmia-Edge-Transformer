BYTES_PER_MIB = 1024 * 1024


# ---------------------------------------------------------------------
#                          Size And Graph Helpers
# ---------------------------------------------------------------------


def file_size_mib(size_bytes: int) -> float:
    """Convert a byte count to mebibytes."""

    if size_bytes < 0:
        raise ValueError("File size must not be negative.")

    return size_bytes / BYTES_PER_MIB


def size_reduction_percentage(fp32_bytes: int, int8_bytes: int) -> float:
    """How much smaller the quantised file is, as a percentage of FP32."""

    if fp32_bytes <= 0:
        raise ValueError("FP32 model size must be positive.")

    if int8_bytes < 0:
        raise ValueError("INT8 model size must not be negative.")

    return (fp32_bytes - int8_bytes) / fp32_bytes * 100.0


def operator_type_counts(model_path: Path) -> dict[str, int]:
    """
    Count node operator types in an ONNX graph.

    Counts are keyed by op_type rather than node name, because node names
    are autogenerated and unstable while the operator mix is exactly what
    quantisation changes.
    """

    import onnx

    model = onnx.load(model_path)

    return dict(Counter(node.op_type for node in model.graph.node))


def summarise_operator_changes(
    fp32_counts: dict[str, int],
    int8_counts: dict[str, int],
) -> dict:
    """
    Describe how quantisation changed the operator mix.

    Quantised operator types are recognised by ONNX Runtime's naming
    convention for integer and quantise/dequantise kernels.
    """

    introduced = sorted(set(int8_counts) - set(fp32_counts))
    removed = sorted(set(fp32_counts) - set(int8_counts))

    reduced = sorted(
        op_type
        for op_type in set(fp32_counts) & set(int8_counts)
        if int8_counts[op_type] < fp32_counts[op_type]
    )

    quantised_present = sorted(
        op_type
        for op_type in int8_counts
        if "Integer" in op_type
        or "QuantizeLinear" in op_type
        or op_type.startswith("QLinear")
    )

    floating_point_remaining = sorted(
        op_type for op_type in int8_counts if op_type not in quantised_present
    )

    return {
        "operator_types_introduced": introduced,
        "operator_types_removed": removed,
        "operator_types_reduced": reduced,
        "quantised_operator_types_present": quantised_present,
        "remaining_floating_point_operator_types": floating_point_remaining,
    }


