def _write_json(payload: dict, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)

    with path.open("w", encoding="utf-8") as file:
        json.dump(payload, file, indent=4)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Create the dynamic INT8 ONNX deployment candidate from the FP32 model."
        )
    )
    parser.add_argument(
        "--input-model-path",
        type=Path,
        default=DEFAULT_INPUT_MODEL_PATH,
    )
    parser.add_argument(
        "--output-model-path",
        type=Path,
        default=DEFAULT_OUTPUT_MODEL_PATH,
    )
    parser.add_argument(
        "--report-path",
        type=Path,
        default=DEFAULT_REPORT_PATH,
    )
    parser.add_argument(
        "--keep-preprocessed-model",
        action="store_true",
        help=(
            "Keep the intermediate pre-processed and value_info-cleaned "
            "FP32 models for debugging."
        ),
    )

    return parser.parse_args()


def main() -> None:
    logging.basicConfig(level=logging.INFO)

    # Extract cli arguments
    args = parse_args()

    # return quantisation, size, validation, and
    # operator metrics
    report = quantize_model(
        input_model_path=args.input_model_path,
        output_model_path=args.output_model_path,
        keep_preprocessed_model=args.keep_preprocessed_model,
    )

    # Write them to our report path
    _write_json(report, args.report_path)

    logger.info("Wrote quantisation report to %s", args.report_path)


if __name__ == "__main__":
    main()
